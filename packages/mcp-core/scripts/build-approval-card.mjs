// Bundles the inline approval card's browser client into a generated module
// that `src/approval-app.ts` inlines as the card's only script.
//
// The card is served inside the host's app frame, so it cannot import anything
// at render time: the CSP it declares allows no origin at all. The MCP Apps
// `App` client ships only as an ES module, so it is bundled here. The output
// is gitignored and rebuilt by `pnpm generate`, which build, typecheck and
// test run first, so no third-party code is committed.
import { writeFileSync } from "node:fs";
import path from "node:path";

import { build } from "esbuild";

const appRoot = path.join(import.meta.dirname, "..");
const entryPoint = path.join(appRoot, "src/approval-card/client.ts");
const bundlePath = path.join(appRoot, "src/approval-card-bundle.generated.ts");

const HEADER = `// GENERATED by scripts/build-approval-card.mjs. Do not edit or commit.
// Source: src/approval-card/client.ts
`;

// The bundle is inlined between <script> tags, so no substring of it may close
// that element or open an HTML comment. Both sequences are rewritten into
// forms JavaScript reads identically.
const inlineSafe = (code) =>
  code.replaceAll("</", String.raw`<\/`).replaceAll("<!--", String.raw`<\!--`);

const result = await build({
  bundle: true,
  entryPoints: [entryPoint],
  format: "iife",
  legalComments: "none",
  minify: true,
  platform: "browser",
  target: ["es2022"],
  tsconfig: path.join(appRoot, "src/approval-card/tsconfig.json"),
  write: false,
});

const [output] = result.outputFiles;

if (!output) {
  throw new Error("esbuild produced no output for the approval card");
}

writeFileSync(
  bundlePath,
  `${HEADER}
export const APPROVAL_CARD_SCRIPT = ${JSON.stringify(inlineSafe(output.text.trim()))};
`
);

console.log(`build-approval-card: wrote ${path.relative(appRoot, bundlePath)}`);
